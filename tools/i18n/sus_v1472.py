EN_EXTRA = {'cm.cube.ctl': 'Control', 'cm.cube.ctlsub': 'Suspensions'}

def en_fallbacks(root):
    out = dict(EN_EXTRA)
    js = io.open(os.path.join(root, 'public', 'caddy-work.js'), encoding='utf-8').read()
    html = io.open(os.path.join(root, 'public', 'index.html'), encoding='utf-8').read()
    for m in re.finditer(r"(?:\bT|_tt|_lvT)\(\s*'((?:cws|cbk)\.[A-Za-z0-9.]+)',\s*'((?:[^'\\]|\\.)*)'", js + html):
        out.setdefault(m.group(1), m.group(2).replace("\\'", "'"))
    return out, html

def q(v): return "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"

if __name__ == '__main__':
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
    en, html = en_fallbacks(root)
    miss = [k for k in TR if k not in en]
    assert not miss, 'no EN fallback in code for: %s' % miss
    lines = html.split('\n')
    anchors = [i for i, l in enumerate(lines) if "'cm.rot.nodayoff':" in l and 'this._t(' not in l]
    assert len(anchors) == 4, anchors
    assert "'cws.sus': " not in html, 'already applied'
    for n, i in enumerate(reversed(anchors)):
        lang = 3 - n            # 0 EN, 1 TH, 2 KO, 3 JA
        pairs = ', '.join(q(k) + ': ' + q(en[k] if lang == 0 else TR[k][lang - 1]) for k in TR)
